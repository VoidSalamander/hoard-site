export function PluginIcon({ plugin, size = "md" }: { plugin: PluginEntry; size?: "md" | "lg" }) {
  const { icon } = plugin;
  const color = plugin.color ?? "#ededed";
  const box = size === "lg" ? "size-14 rounded-xl" : "size-11 rounded-lg";
  const glyph = size === "lg" ? "size-7" : "size-5";
  let inner;
  if ("lucide" in icon) {
    const Icon = icon.lucide;
    inner = <Icon className={glyph} style={{ color }} aria-hidden />;
  } else if ("brand" in icon) {
    inner = (
      <svg viewBox="0 0 24 24" className={glyph} fill={color} aria-hidden>
        <path d={BRANDS[icon.brand]} />
      </svg>
    );
  } else {
    inner = (
      <span className={`font-mono font-bold ${size === "lg" ? "text-lg" : "text-sm"}`} style={{ color }} aria-hidden>
        {icon.letter}
      </span>
    );
  }
  return (
    <span
      className={`grid shrink-0 place-items-center border border-ink-600 bg-ink-900 ${box}`}
      style={plugin.color ? { boxShadow: `inset 0 -2px 0 ${plugin.color}55` } : undefined}
    >
      {inner}
    </span>
  );
}
